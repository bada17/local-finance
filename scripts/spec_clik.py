def 의회목록받기():
    # 수집기가 이미 구워 둔 것이 있으면 그걸 쓴다 — 없어진 의회 5곳이 거기 붙어 있다.
    구운것 = os.path.join(ROOT, 'data', 'clik', '의회목록.json')
    if os.path.exists(구운것):
        import json
        return [(d['rasmblyId'], d['의회명'], d['지역코드'],
                 '있다' if d.get('지금있나', True) else f"없어졌다 — {d.get('까닭', '')}")
                for d in json.load(open(구운것, encoding='utf-8'))]
    req = urllib.request.Request(명세주소, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        h = r.read().decode('utf-8', 'replace')
    i = h.find('id="rasmblyIdDownDiv"')
    if i < 0:
        raise SystemExit('명세 페이지에서 의회 코드표를 못 찾았다 — 페이지가 바뀌었다')
    조각 = html.unescape(re.sub(r'(?s)<[^>]+>', chr(1), h[i:]))
    토막 = [t.strip() for t in 조각.split(chr(1)) if t.strip()]
    본것, 목록 = set(), []
    for 앞, 뒤 in zip(토막, 토막[1:]):
        if re.fullmatch(r'\d{6}', 뒤) and re.search(r'[가-힣]', 앞) \
                and not re.fullmatch(r'\d{6}', 앞):
            if 뒤 not in 본것:
                본것.add(뒤)
                목록.append((뒤, 앞, 뒤[:3], '있다'))
    return 목록


머리칠 = PatternFill('solid', fgColor='DDE6F0')


def 판(wb, 이름, 머리, 줄들, 너비):
    ws = wb.create_sheet(이름)
    ws.append(머리)
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = 머리칠
    for 줄 in 줄들:
        ws.append(list(줄))
    for i, w in enumerate(너비, start=1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    ws.freeze_panes = 'A2'
    for 행 in ws.iter_rows(min_row=2):
        for c in 행:
            c.alignment = Alignment(vertical='top', wrap_text=True)
    return ws


