def 기준과해(글):
    """공시 묶음의 기준(예산·결산)과 회계연도 — 문서 글자에서.
    기준: 결산에만 있는 양식 칸과 예산에만 있는 양식 칸 가운데 어느 쪽이 더 많이 나오나(받은 파일에서 본 칸 이름).
      ⚠️ 1-1 칸 이름으로 가르면 틀린다 — 제천 결산공시(2026년 FY2025)는 1-1 을 「예산 규모」라 적었다.
      그런 칸이 없으면 앞머리의 「○○기준」.
    해: 앞머리(3,000자)에 「20xx년·20xx회계연도·FY20xx·'xx년」으로 가장 많이 나온 해(같으면 큰 해)."""
    결 = sum(1 for w in 결산칸 if re.search(번호 + 느슨(w), 글))
    예 = sum(1 for w in 예산칸 if re.search(번호 + 느슨(w), 글))
    if 결 or 예:
        기준 = '결산' if 결 > 예 else '예산'
    else:
        m = re.search(r'(예산|결산)\s*기준|\((예산|결산)\)|(예산|결산)\s*공시', 글[:3000])
        기준 = (m.group(1) or m.group(2) or m.group(3)) if m else ''
    해들 = collections.Counter()
    for m in re.finditer(r"(20[1-3]\d)\s*(?:년|회계연도)|FY\s*(20[1-3]\d)|['’‘](\d\d)\s*(?:년|회계연도)", 글[:3000]):
        해들[int(m.group(1) or m.group(2) or ('20' + m.group(3)))] += 1
    해 = max(해들, key=lambda y: (해들[y], y)) if 해들 else None
    return 기준, 해


