def 칸뽑기(q, 자료):
    """질문이 쓰는 **칸 이름**을 실제 자료에서 꺼낸다."""
    이름들 = []
    if '축' in q:
        열쇠, 축 = q['축']
        이름들 += 자료.get(열쇠, {}).get('축별', {}).get(축, [])
    이름들 += q.get('칸', [])
    이름들 = [n for n in 이름들 if n not in q.get('빼기', [])]
    본 = set()
    나온 = []
    for n in 이름들:
        if n not in 본:
            본.add(n)
            나온.append({'이름': n, '뜻': 뜻.get(n) or 자료칸뜻.get(n, '')})
    return 나온


