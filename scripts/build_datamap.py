def 크기(*길들):
    총, 수 = 0, 0
    for g in 길들:
        for p in glob.glob(os.path.join(ROOT, g)):
            if os.path.isfile(p):
                총 += os.path.getsize(p)
                수 += 1
    return 총, 수


def 보기좋게(b):
    for 단위, 몫 in (('MB', 1 << 20), ('KB', 1 << 10)):
        if b >= 몫:
            return f'{b / 몫:,.0f}{단위}'
    return f'{b}B'


def js(p):
    with open(os.path.join(ROOT, p), encoding='utf-8') as f:
        return json.load(f)


def 파일들(길들):
    """지정된 자료 위치만 읽는다. 디렉터리·빈 파일은 자료로 세지 않는다."""
    return sorted({p for g in 길들 for p in glob.glob(os.path.join(ROOT, g))
                   if os.path.isfile(p) and os.path.getsize(p) > 0})


def json자료있나(p):
    try:
        읽기 = gzip.open if p.endswith('.gz') else open
        with 읽기(p, 'rt', encoding='utf-8-sig') as f:
            d = json.load(f)
        return isinstance(d, (dict, list)) and bool(d)
    except (OSError, ValueError, EOFError):
        return False


