ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, 'site')


def 있나(*길들):
    return any(glob.glob(os.path.join(ROOT, g)) for g in 길들)


def 크기(*길들):
    총, 수 = 0, 0
    for g in 길들:
        for p in glob.glob(os.path.join(ROOT, g)):
            if os.path.isfile(p):
                총 += os.path.getsize(p)
                수 += 1
    return 총, 수


def 보기좋게(b):
    for 단위, 몫 in (('MB', 1 << 20), ('KB', 1 << 10)):
        if b >= 몫:
            return f'{b / 몫:,.0f}{단위}'
    return f'{b}B'


def js(p):
    with open(os.path.join(ROOT, p), encoding='utf-8') as f:
        return json.load(f)


